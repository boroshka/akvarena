<?php
/**
 * Обработчик формы «Написать нам» — akvarena.ru
 * ------------------------------------------------------------------
 * Отправляет письмо напрямую через встроенную в хостинг функцию mail(),
 * без сторонних сервисов вроде Formspree. Подтверждать почтовый ящик
 * не нужно — сервер сам формирует и отправляет письмо.
 *
 * Куда приходят заявки — задаётся ОДНОЙ строкой ниже (TO_EMAIL).
 * Больше нигде в этом файле ничего менять не нужно.
 * ------------------------------------------------------------------
 */

// -------- НАСТРОЙКА: на какой адрес присылать заявки --------
const TO_EMAIL = 'akvarena@mail.ru';
// --------------------------------------------------------------

// Страница, куда вернуть посетителя после отправки (с якорем на форму).
const REDIRECT_BASE = 'index.html';

function back(string $status): void {
    header('Location: ' . REDIRECT_BASE . '?sent=' . $status . '#napisat', true, 303);
    exit;
}

// Форма отправляется только методом POST — прямые заходы на этот файл отбрасываем.
if (($_SERVER['REQUEST_METHOD'] ?? '') !== 'POST') {
    header('Location: ' . REDIRECT_BASE, true, 303);
    exit;
}

// Скрытая ловушка для ботов: настоящий посетитель это поле никогда не заполняет.
// Если оно не пустое — письмо не шлём, но посетителю (боту) показываем «успех»,
// чтобы не подсказывать, что его отфильтровали.
if (trim($_POST['_gotcha'] ?? '') !== '') {
    back('1');
}

// Обрезаем строку до максимальной длины, не разрывая многобайтовый символ
// (кириллицу) посередине. Если на сервере нет расширения mbstring —
// используем обычную substr(), чтобы форма в любом случае работала.
function safe_cut(string $v, int $maxLen): string {
    if (function_exists('mb_substr')) {
        return mb_substr($v, 0, $maxLen);
    }
    return substr($v, 0, $maxLen);
}

// Убираем возможные переводы строк из полей — так их нельзя подставить
// в заголовки письма (защита от «header injection»), даже если это поле
// в будущем начнут использовать в заголовке.
function clean_field(string $v, int $maxLen): string {
    $v = str_replace(["\r", "\n"], ' ', $v);
    $v = trim($v);
    return safe_cut($v, $maxLen);
}

$name    = clean_field($_POST['name']    ?? '', 120);
$phone   = clean_field($_POST['phone']   ?? '', 40);
$message = trim(str_replace("\r\n", "\n", $_POST['message'] ?? ''));
$message = safe_cut($message, 4000);

if ($name === '' || $phone === '' || $message === '') {
    back('0');
}

// Тело письма — обычный текст.
$body  = "Новая заявка с сайта akvarena.ru\n";
$body .= "-----------------------------------\n";
$body .= "Имя:      $name\n";
$body .= "Телефон:  $phone\n";
$body .= "\nСообщение:\n$message\n";
$body .= "-----------------------------------\n";
$body .= 'Отправлено: ' . date('d.m.Y H:i') . "\n";

$subject = '=?UTF-8?B?' . base64_encode('Новое сообщение с сайта АквАрена') . '?=';

// Адрес отправителя — на домене сайта. Не обязан быть реальным почтовым
// ящиком: это стандартная практика для писем «от сайта», и так меньше
// риск, что письмо попадёт в спам (некоторые серверы проверяют, что
// отправитель принадлежит тому же домену, с которого ушло письмо).
$host = preg_replace('/^www\./i', '', $_SERVER['HTTP_HOST'] ?? 'akvarena.ru');
$from = 'no-reply@' . $host;

$headers   = [];
$headers[] = 'From: АквАрена — сайт <' . $from . '>';
$headers[] = 'MIME-Version: 1.0';
$headers[] = 'Content-Type: text/plain; charset=UTF-8';
$headers[] = 'X-Mailer: PHP/' . phpversion();

$ok = @mail(TO_EMAIL, $subject, $body, implode("\r\n", $headers));

back($ok ? '1' : '0');
